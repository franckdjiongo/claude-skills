export const getSkillsByCategory = (categoryId: string): Skill[] => {
  if (categoryId === 'all') return skills;
  return skills.filter(skill => skill.category === categoryId);
};

export const searchSkills = (query: string): Skill[] => {
  const lowerQuery = query.toLowerCase();
  return skills.filter(skill =>
    skill.name.toLowerCase().includes(lowerQuery) ||
    skill.description.toLowerCase().includes(lowerQuery) ||
    skill.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
  );
};

export const getSkillById = (id: string): Skill | undefined => {
  return skills.find(skill => skill.id === id);
};

export const getRepositoryColor = (repo: string): string => {
  switch (repo) {
    case 'claude-skills':
      return 'var(--accent-cyan)';
    case 'superpowers':
      return 'var(--accent-magenta)';
    case 'anthropic-skills':
      return 'var(--accent-gold)';
    default:
      return 'var(--accent-cyan)';
  }
};
